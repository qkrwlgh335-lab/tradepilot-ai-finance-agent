// Independent formula, not generated by runCounterfactual:
// USD out 100k@2m + delayed USD in 300k@4m + EUR out 80k@4m,
// each |net| × rate × annual σ × sqrt(months/12) × 1.645.
const EXPECTED_DELAY_CFAR = 49_297_391;
const EXPECTED_ADVERSE_FX_PNL = -19_864_200;

test("payment delay targets a transaction by id and re-runs the engines (exact golden)", () => {
  const result = runCounterfactual(
    "payment_delay_1m",
    GOLDEN_INPUT,
    deps(),
    { targetTransactionId: "txn-usd-in-3m" },
  );

  assert.equal(result.scenario.targetTransactionId, "txn-usd-in-3m");
  assert.deepEqual(result.changedInputs, [{
    path: "transactions.id~00740078006e002d007500730064002d0069006e002d0033006d.months",
    before: 3,
    after: 4,
  }]);
  assert.equal(Math.round(result.after.cfar.total), EXPECTED_DELAY_CFAR);
  assert.notDeepEqual(result.before.liquidity, result.after.liquidity);
});

