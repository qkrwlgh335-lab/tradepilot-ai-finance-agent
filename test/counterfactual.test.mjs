test("recommendations are re-derived, carry reasoning paths and never gain score/rank", () => {
  const result = runCounterfactual("revenue_drop_30", GOLDEN_INPUT, deps());
  for (const key of ["added", "removed", "movedToPending"])
    assert.ok(Array.isArray(result.affectedRecommendations[key]));
  assert.deepEqual(result.after.recommendations.candidates.map((candidate) => candidate.product_id), [
    "fx_insurance",
    "trade_loan",
    "ecg_pre",
  ]);
  for (const candidate of result.after.recommendations.candidates) {
    assert.ok(candidate.reasoningPath.length > 0);
    assert.ok(!("score" in candidate) && !("rank" in candidate));
  }
  assert.doesNotMatch(JSON.stringify(result.after.recommendations), /"(score|rank)"\s*:/);
});

test("a candidate moved to pending is reported once, never also as removed", () => {
  let recommendationCall = 0;
  const product = { purpose: "fx_hedge", product_id: "demo_product" };
  const transitionDeps = deps();
  transitionDeps.engines.reasoner = {
    recommend() {
      recommendationCall += 1;
      return recommendationCall === 1
        ? { candidates: [product], pending: [], excluded: [], unavailable: [] }
        : { candidates: [], pending: [product], excluded: [], unavailable: [] };
    },
  };

  const result = runCounterfactual("payment_delay_1m", GOLDEN_INPUT, transitionDeps);
  assert.deepEqual(result.affectedRecommendations.removed, []);
  assert.deepEqual(result.affectedRecommendations.movedToPending, [{
    product_id: "demo_product",
    purpose: "fx_hedge",
    from: "candidate",
    to: "needs_information",
  }]);
});

test("LLM-proposed changes run only when they match the approved scenario schema", () => {
  assert.equal(validateScenarioProposal({
    id: "made_up",
    changes: [{ path: "cfar.total", after: 0 }],
  }).ok, false);
  assert.equal(validateScenarioProposal({
    id: "payment_delay_1m",
    changes: [{ path: "transactions.txn-usd-in-3m.months", after: 4 }],
  }).ok, false);
  assert.equal(validateScenarioProposal({
    id: "payment_delay_1m",
    changes: [{
      path: "transactions.id~00740078006e002d007500730064002d0069006e002d0033006d.months",
      after: 4,
    }],
  }).ok, true);
  assert.equal(validateScenarioProposal({
    id: "payment_delay_1m",
    changes: [{ path: "cfar.total", after: 0 }],
  }).ok, false);
});

test("LLM proposal paths reject prototype traversal segments, including encoded forms", () => {
  for (const path of [
    "rates.__proto__",
    "rates.constructor",
    "rates.prototype",
    "rates.%5F%5Fproto%5F%5F",
    "transactions.constructor.months",
    "transactions.%255F%255Fproto%255F%255F.months",
  ]) {
    const id = path.startsWith("rates.") ? "adverse_fx_5" : "payment_delay_1m";
    assert.equal(validateScenarioProposal({
      id,
      changes: [{ path, after: 1 }],
    }).ok, false, path);
  }

  assert.equal(validateScenarioProposal({
    id: "adverse_fx_5",
    changes: [{ path: "rates.USD", after: 950 }],
  }).ok, true);
});

