test("revenue drop states its scope and recomputes without a monotonicity claim", () => {
  const result = runCounterfactual(
    "revenue_drop_30",
    GOLDEN_INPUT,
    deps(),
    { scope: "all_receivables" },
  );
  assert.match(result.scenario.targetScopeLabel, /모든 수취/);
  assert.equal(result.changedInputs.length, 1);
  for (const change of result.changedInputs)
    assert.equal(Math.round(change.after), Math.round(change.before * 0.7));
  assert.notDeepEqual(result.before.cfar, result.after.cfar);
  assert.ok(result.explanationFacts.every((fact) => !/위험.*개선|안전해졌/.test(fact.text)));
});

