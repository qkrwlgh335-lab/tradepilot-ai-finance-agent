test("percent-bearing transaction ids generate paths accepted by the same allowlist", () => {
  for (const transactionId of ["%", "%E0%A4%A", "%5F%5Fproto%5F%5F"]) {
    const input = structuredClone(GOLDEN_INPUT);
    input.transactions[0].transaction_id = transactionId;
    const result = runCounterfactual(
      "payment_delay_1m",
      input,
      deps(),
      { targetTransactionId: transactionId },
    );
    assert.equal(
      isAllowedChangePath("payment_delay_1m", result.changedInputs[0].path),
      true,
      transactionId,
    );
  }
});

test("distinct transaction ids always produce distinct change-path segments", () => {
  const transactionIds = ["__proto__", "id:__proto__", "constructor", "id:constructor"];
  const paths = transactionIds.map((transactionId) => {
    const input = structuredClone(GOLDEN_INPUT);
    input.transactions[0].transaction_id = transactionId;
    return runCounterfactual(
      "payment_delay_1m",
      input,
      deps(),
      { targetTransactionId: transactionId },
    ).changedInputs[0].path;
  });

  assert.equal(new Set(paths).size, transactionIds.length);
});

